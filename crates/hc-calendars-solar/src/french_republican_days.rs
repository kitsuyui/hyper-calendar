#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_lists_are_where_their_sources_put_them() {
        let name = |list: &hc_calendar::shape::Naming<366>, month, day| {
            list.name(day_index(month, day).unwrap())
        };
        // Larousse's pairs of a saint's day and the Republican day: François
        // on 13 vendémiaire, Potiron; Catherine on 5 frimaire, Cochon;
        // Victor on 3 thermidor, Melon; Frédéric on 8 floréal, Champignon;
        // Prosper on 7 messidor, Concombre; Zacharie on 15 brumaire,
        // Dindon (Grand dictionnaire universel, t. 3, 1867, secondary).
        for (month, day, expected) in [
            (1, 13, "Potiron"),
            (3, 5, "Cochon"),
            (11, 3, "Melon"),
            (8, 8, "Champignon"),
            (10, 7, "Concombre"),
            (2, 15, "Dindon"),
        ] {
            assert_eq!(name(&IN_USE, month, day), expected);
            assert_eq!(name(&FABRE_1793, month, day), expected);
        }
        assert_eq!(name(&IN_USE, 1, 1), "Raisin");
        assert_eq!(name(&ENGLISH, 1, 1), "Grape");
        assert_eq!(name(&IN_USE, 4, 1), "Tourbe");
        assert_eq!(name(&FABRE_1793, 4, 1), "Neige");
        assert_eq!(name(&IN_USE, 12, 30), "Panier");
        assert_eq!(name(&FABRE_1793, 12, 30), "Corbeille");
        assert_eq!(name(&IN_USE, 13, 6), "Jour de la Révolution");
        assert_eq!(name(&FABRE_1793, 13, 6), "La Sanculottide");
        assert_eq!(name(&FABRE_1793, 13, 1), "Fête de la Vertu");
        assert_eq!(day_index(13, 7), None);
        assert_eq!(day_index(1, 31), None);
        assert_eq!(day_index(0, 1), None);
        assert_eq!(day_index(12, 30), Some(359));
        let differ = (0..366)
            .filter(|index| IN_USE.name(*index) != FABRE_1793.name(*index))
            .count();
        assert_eq!(differ, 100);
    }
}
