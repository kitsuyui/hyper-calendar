//! The names of the days of the French Republican year: the *calendrier
//! rural* that put "all the objects that make up the true national wealth"
//! in place of the saints, a plant or fruit on most days, an animal on
//! each *quintidi* and a tool on each *décadi*.
//!
//! Fabre d'Églantine's report of 3 brumaire an II (24 October 1793)
//! explains the names: "the priests had assigned to each day of the year
//! the commemoration of a so-called saint", and "the nation, having driven
//! this crowd of the canonised out of its calendar, should find in their
//! place all the objects that make up the true national wealth"; the
//! decree at its end adopts "the table annexed to this decree" (Fabre
//! d'Églantine, *Rapport ... sur le calendrier*, Imprimerie nationale,
//! 1793, in Wikisource's transcription, `fabre-1793-rapport`, read
//! 2026-09-29). The decree of 4 frimaire an II names only the months and
//! the days of the *décade*; its annexed *annuaire* carried "the names of
//! the days and of the months", and Wikisource's transcription stops before
//! it (`decret-4-frimaire-an-ii`).
//!
//! Two lists, two names (policy §5): [`FABRE_1793`], the table of the
//! report, the one primary list read, and [`IN_USE`], the list both
//! Wikipedias print, French Wikipedia after Millin de Grandmaison's
//! *Annuaire du républicain* (1793–1794), not read
//! (`frwiki-calendrier-republicain`, secondary). They agree on 266 of the
//! 366 names once Fabre's capitals are set in the others' case and his
//! apostrophe is the ASCII one; they differ only in spelling on 42, name
//! different things on 53 — most of Nivôse among them, Fabre's snow, ice,
//! honey and wax becoming peat, coal, bitumen and sulphur, and the sixth
//! complementary day — and call the other five complementary days *Fête*
//! where the list in use has *Jour*. [`ENGLISH`] is
//! English Wikipedia's gloss of each name in [`IN_USE`]
//! (`wikipedia-french-republican-calendar`, secondary), which spells
//! thirteen of the French names differently from French Wikipedia.
//!
//! Each list is 366 names, day 1 of Vendémiaire first, the 360 days of the
//! months and then the six complementary days, the sixth only in a
//! sextile year: [`day_index`] maps a date to its place. Fabre's table
//! prints each *décadi* in capitals and each *quintidi* in small capitals;
//! the names here are in the case of the other days, and its leap day,
//! "LA SANCULOTTIDE", is "La Sanculottide". Its apostrophes are the ASCII
//! one.

/// The position of day `day` of month `month` (13 for the complementary
/// days) in the lists, from 0; `None` for a day no year has.
#[must_use]
pub const fn day_index(month: u8, day: u8) -> Option<usize> {
    match month {
        1..=12 if day >= 1 && day <= 30 => Some((month as usize - 1) * 30 + day as usize - 1),
        13 if day >= 1 && day <= 6 => Some(360 + day as usize - 1),
        _ => None,
    }
}

