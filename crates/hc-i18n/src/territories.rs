/// One locale's names for the [`REGIONS`].
#[derive(Debug, Clone, Copy)]
pub struct TerritoryNames {
    /// The BCP 47 tag, spelled as [`crate::data::LOCALES`] spells it.
    pub tag: &'static str,
    /// The names in [`REGIONS`] order, each followed by a line feed; an
    /// empty line where CLDR has no release-level name.
    names: &'static str,
}

impl TerritoryNames {
    /// The name of the region at `index` in [`REGIONS`], if the locale has
    /// one.
    #[must_use]
    pub fn name_at(&self, index: usize) -> Option<&'static str> {
        self.names
            .split('\n')
            .nth(index)
            .filter(|name| !name.is_empty())
    }

    /// The name of `region`, an ISO 3166-1 alpha-2 code in any case, if it
    /// is one of the [`REGIONS`] and the locale names it.
    #[must_use]
    pub fn name_of(&self, region: &str) -> Option<&'static str> {
        region_index(region).and_then(|index| self.name_at(index))
    }
}

/// A territory's name and the tag of the table that gave it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TerritoryName {
    /// What the locale calls the territory.
    pub name: &'static str,
    /// The tag of the table that answered: `de` for a request for `de-AT`.
    pub tag: &'static str,
}

/// The position of `region` in [`REGIONS`], matched without regard to
/// case.
#[must_use]
pub fn region_index(region: &str) -> Option<usize> {
    let [first, second] = <[u8; 2]>::try_from(region.as_bytes()).ok()?;
    let wanted = [first.to_ascii_uppercase(), second.to_ascii_uppercase()];
    REGIONS
        .binary_search_by(|code| code.as_bytes().cmp(&wanted[..]))
        .ok()
}

/// The table for a data tag, spelled as [`TerritoryNames::tag`] is.
#[must_use]
pub fn table(tag: &str) -> Option<&'static TerritoryNames> {
    TABLES.iter().find(|table| table.tag == tag)
}

/// What `locale` calls `region`, from the first table in its fallback
/// chain that names it; `None` when none does, the root locale included.
#[must_use]
pub fn territory_name(locale: &Locale, region: &str) -> Option<TerritoryName> {
    let index = region_index(region)?;
    locale.fallback().find_map(|candidate| {
        TABLES
            .iter()
            .filter(|table| candidate.matches_tag(table.tag))
            .find_map(|table| {
                table.name_at(index).map(|name| TerritoryName {
                    name,
                    tag: table.tag,
                })
            })
    })
}

