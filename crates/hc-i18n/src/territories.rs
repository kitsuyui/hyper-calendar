//! What a locale calls a territory, as data: Unicode CLDR 48's territory
//! display names for the regions the workspace keeps holiday tables for.
//!
//! The names are CLDR 48's, the `release-48` tag of
//! <https://github.com/unicode-org/cldr>, `common/main/<locale>.xml`,
//! `localeDisplayNames/territories/territory`, read 2026-09-27 for every
//! locale below: `zh.xml` for `zh-Hans`, `zh_Hant.xml` for `zh-Hant`, and
//! the file of the same tag for the rest [cldr48-territory-names]. As for
//! the calendar names in [`crate::data`], only the plain value of each
//! territory is taken — not its `alt="short"` or `alt="variant"` form, so
//! Hong Kong is `Hong Kong SAR China` in English and not `Hong Kong` — and
//! only at CLDR's release levels, `approved` and `contributed`. A
//! `provisional` or `unconfirmed` value is a proposal the release does not
//! stand behind, and is left out.
//!
//! # Which regions
//!
//! Not every territory CLDR names: only the [`REGIONS`], the 195 ISO 3166-1
//! codes `hc-holiday` keeps a country's table for, which include every
//! country an exchange's table takes its days off from. The facade's
//! `holiday_lines` tests hold the two lists together. CLDR names about 300
//! territories in most locales, and the rest — the continents, the
//! dependencies, `EU` and `UN` — name nothing a table here is keyed by.
//!
//! # What is carried, and what is not
//!
//! Every locale `hc-i18n` carries whose CLDR file names at least one of the
//! regions at a release level has a table: 35 of the 41. Most name all 195.
//! Kabyle (`kab`) has no release-level name for Hong Kong, North Macedonia,
//! Macao, Montenegro, Serbia or South Sudan, and Standard Moroccan Tamazight
//! (`zgh`) none for Hong Kong, North Macedonia or Macao; their other
//! values are there. Tibetan (`bo`) and Sanskrit (`sa`) name ten regions
//! each, and every Coptic (`cop`) value is unconfirmed, so Coptic has no
//! table. Balinese, Middle Egyptian, Nahuatl, Yucatec Maya and Zapotec have
//! no file in CLDR 48 and no table. A region a locale has no name for is
//! left unnamed, never filled from another language: a caller that needs a
//! name falls back itself, as `hc_holiday_tables` falls back to the table's
//! English name.
//!
//! The values are CLDR's as published, including where one reads oddly:
//! Sanskrit's `GB`, `संयुक्त राष्ट्र:`, is the release's approved value.
//!
//! # Compact by design
//!
//! Thirty-five tables of 195 names would be some seven thousand string
//! slices, eight bytes each on `wasm32` before a byte of text. So each table
//! is one string, its names in [`REGIONS`] order separated by line feeds,
//! with an empty line where the locale has no name; the source keeps each
//! name beside its code through the `territory_names!` macro, which checks the codes
//! against [`REGIONS`] at compile time and keeps only the names. The whole
//! module is behind the `territories` feature, so that a build that names
//! no territory — the calendars layer of the WebAssembly module — does not
//! carry the hundred kilobytes of text.
//!
//! # Locales
//!
//! Lookup walks [`Locale::fallback`] as the rest of the crate does, and
//! takes the first table in the chain that names the region: `de-AT` finds
//! `de`, `zh-TW` finds `zh-Hant`, and `ja-JP` finds `ja`. The root locale
//! has no table, so a chain that reaches it names nothing.

