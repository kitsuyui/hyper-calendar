/// Whether `codes` are exactly [`REGIONS`], in order: the compile-time
/// check of `territory_names!`.
const fn same_regions(codes: &[&str]) -> bool {
    if codes.len() != REGIONS.len() {
        return false;
    }
    let mut index = 0;
    while index < codes.len() {
        let (left, right) = (codes[index].as_bytes(), REGIONS[index].as_bytes());
        if left.len() != right.len() {
            return false;
        }
        let mut byte = 0;
        while byte < left.len() {
            if left[byte] != right[byte] {
                return false;
            }
            byte += 1;
        }
        index += 1;
    }
    true
}

/// One table: every region's code followed by its name, `""` where the
/// locale has none. The codes must be [`REGIONS`], in order, or the build
/// fails; only the names, each followed by a line feed, are kept.
macro_rules! territory_names {
    ($($region:ident $name:literal)*) => {{
        const _: () = assert!(
            same_regions(&[$(stringify!($region)),*]),
            "a territory table's codes are not REGIONS in order"
        );
        concat!($($name, "\n"),*)
    }};
}

