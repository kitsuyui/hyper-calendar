//! The Earth's heliocentric position from VSOP87, truncated for a calendar's
//! needs.
//!
//! VSOP87 (Bretagnon and Francou, *Astronomy and Astrophysics* 202, 1988) is
//! the planetary theory behind every modern almanac's Sun. Series D gives
//! heliocentric spherical coordinates referred to the ecliptic and equinox of
//! date: longitude and latitude in radians, distance in astronomical units,
//! each as a sum over powers of *τ*, the time in Julian millennia from
//! J2000.0 TD, of terms *A* cos(*B* + *C* τ).
//!
//! # The truncation, and what it costs
//!
//! The full Earth series has 2 425 terms. The tables here keep every term
//! whose amplitude *A* is at least 10⁻⁷ — radians for *L* and *B*, AU for
//! *R* — which is 213 of them, and the cut was measured rather than assumed:
//! against the full series, sampled every seven years from 1000 to 3000, the
//! truncated longitude is within **0.23″**, the latitude within 0.13″ and the
//! distance within 10⁻⁶ AU (150 km). The Sun moves 1″ in 24 seconds, so the
//! longitude cut costs under six seconds of time at an equinox — well inside
//! what ΔT itself is uncertain by.
//!
//! Meeus's Appendix III is a different truncation of the same theory, and
//! his example 25.b is the check below.
//!
//! # Provenance
//!
//! The coefficients are the file `VSOP87D.ear` of the IMCCE distribution
//! (Bureau des longitudes, Paris; obtained from the mirror at
//! `github.com/ctdk/vsop87`, retrieved 2026-09-22), copied verbatim in the
//! file's own precision; the selection was scripted, not typed.

// The coefficients below are the file's, verbatim, in the file's own
// precision; rounding them to what f64 distinguishes would be a second
// transcription with nothing to check it against, and a phase that happens
// to be π is the file's π, not the language's.
#![allow(clippy::excessive_precision, clippy::approx_constant)]

use hc_core::math::cos;

/// One term of a series: amplitude, phase and frequency.
#[derive(Debug, Clone, Copy, PartialEq)]
struct Term(f64, f64, f64);

/// The Earth's heliocentric ecliptic longitude and latitude in radians and
/// its distance from the Sun in astronomical units, at `millennia` Julian
/// millennia from J2000.0 in dynamical time.
#[must_use]
pub fn earth_heliocentric(millennia: f64) -> (f64, f64, f64) {
    (
        sum_series(EARTH_L, millennia),
        sum_series(EARTH_B, millennia),
        sum_series(EARTH_R, millennia),
    )
}

/// Σ over powers of the sum of each power's terms.
fn sum_series(series: &[&[Term]], millennia: f64) -> f64 {
    let mut total = 0.0;
    let mut power = 1.0;
    for terms in series {
        let mut sum = 0.0;
        for Term(amplitude, phase, frequency) in *terms {
            sum += amplitude * cos(phase + frequency * millennia);
        }
        total += sum * power;
        power *= millennia;
    }
    total
}

