#[test]
fn a_date_is_written_as_the_locale_writes_it() {
    let registry = registry();
    for (tag, calendar, used, expected) in PINS {
        let locale: Locale = tag.parse().expect("a carried tag");
        let calendar = registry.get_by_name(calendar).expect("registered");
        let fields = calendar.fixed_to_fields(DAY).expect("converts");
        let writer = label::locale_for(calendar, Some(&locale));
        assert_eq!(
            (
                names::locale_data(&writer).tag,
                label::date(calendar, &fields, &writer).as_str()
            ),
            (*used, *expected),
            "{tag} {}",
            calendar.meta().id.0
        );
    }
}

#[test]
fn every_carried_locale_has_its_dates_pinned() {
    for data in LOCALES {
        for calendar in ["gregory", "buddhist", "persian", "japanese"] {
            assert!(
                PINS.iter()
                    .any(|(tag, id, _, _)| *tag == data.tag && *id == calendar),
                "{} {calendar}",
                data.tag
            );
        }
    }
}
